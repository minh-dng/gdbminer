"""Flash, trace, mine and evaluate one configuration, with retries and resume.

Every stage runs in its own process group (`start_new_session`) and is stopped with `killpg`, so
a hung trace.py goes together with the GDB, OpenOCD and serial worker it started, and no process
of another session is touched. A non-zero exit or a timeout is a failure and is retried. A
failure while a device is unplugged is not counted: the next stage waits until it is back.

trace.py has no option to skip seeds: it traces every seed of `seed_directory` into a new
`trial-N`. A trace retry therefore copies the seeds without a trace into `resume-k/seeds`,
traces them with a generated TOML that points there, and copies the new traces into the main
trial. The missing seeds are derived from the complete traces present, so a restarted runner
resumes the same way. mine.py and precision_recall.py read the latest `trial-N` of
`output_directory`, which the generated TOML points to the scratch folder, so they always see the
merged trial.

Retries are counted per failure: a trace retry that adds traces resets the count, so a long run
with rare, unrelated stops goes on while the same stop repeating gives up.
"""

import json
import os
import re
import shlex
import shutil
import signal
import subprocess
import sys
import time
from collections.abc import Callable
from contextlib import suppress
from itertools import zip_longest
from pathlib import Path
from typing import IO

from scripts.eval_runner import layout
from scripts.eval_runner.devices import ADAPTER, UART, Board
from util import load_config

TRACE = "src/tracer/trace.py"
MINE = "src/miner/mine.py"
EVALUATE = "src/eval/precision_recall.py"
# Seconds for the USB devices to re-enumerate after a failure or an upload.
RETRY_PAUSE = 30
FLASH_SETTLE = 5
# Seconds between SIGTERM and SIGKILL to the process group.
STOP_GRACE = 10


class ConfigError(Exception):
    """A configuration or consistency error: retrying cannot fix it, so the config stops."""


class StageFailed(Exception):
    """A stage failed more than `--max-retries` times in a row."""


def seed_files(seed_directory: Path) -> list[Path]:
    """The seeds trace.py traces: the files of the seed folder."""
    return sorted(path for path in seed_directory.iterdir() if path.is_file())


def complete(trace: Path) -> bool:
    """Whether `trace` is whole JSON: a stop while trace.py or a copy writes it leaves a part."""
    try:
        json.loads(trace.read_bytes())
    except (OSError, ValueError):
        return False
    return True


def missing_seeds(seed_directory: Path, trial: Path) -> list[Path]:
    """The seeds without a complete `<seed>.trace` in `trial`."""
    return [
        seed for seed in seed_files(seed_directory) if not complete(trial / f"{seed.name}.trace")
    ]


def merge_traces(resume: Path, trial: Path) -> None:
    """Copy the complete traces of `resume/trial-*` that `trial` lacks."""
    for trace in sorted(resume.glob("trial-*/*.trace")):
        if complete(trace) and not complete(trial / trace.name):
            shutil.copy2(trace, trial)


def check_traces(seed_directory: Path, trial: Path) -> None:
    """Require the pairs mine.py builds to match: it pairs `sorted(trial.glob("*.trace"))` with
    `sorted(seed_directory.glob("*"))` by position, so names alone are not enough."""
    seeds = [seed.name for seed in sorted(seed_directory.glob("*"))]
    traces = [trace.name.removesuffix(".trace") for trace in sorted(trial.glob("*.trace"))]
    for trace, seed in zip_longest(traces, seeds):
        if trace != seed:
            raise ConfigError(f"mine.py would pair the trace of {trace} with the seed {seed}")


def generated_toml(source: Path, output_directory: Path, seed_directory: Path | None = None) -> str:
    """The text of `source` with `output_directory` (and `seed_directory`) replaced."""
    text = source.read_text(encoding="utf-8")
    changes = {"output_directory": output_directory, "seed_directory": seed_directory}
    for key, value in changes.items():
        if value is not None:
            # A JSON string is a valid TOML basic string.
            text, count = re.subn(
                rf"^{key}\s*=.*$", f"{key} = {json.dumps(str(value))}", text, flags=re.MULTILINE
            )
            if count != 1:
                raise ConfigError(f"{source}: expected one '{key} =' line, found {count}")
    changed = " and ".join(key for key, value in changes.items() if value is not None)
    return f"# Generated by scripts/eval_runner from {source}: {changed} changed.\n{text}"


def run_in_group(command: list[str], log: IO[str], timeout: float) -> tuple[int, bool]:
    """Run `command` in a new process group; return its exit status and whether it timed out.

    The group is stopped afterwards in every case (normal exit, timeout, Ctrl-C): an OpenOCD or
    serial worker left by a crashed trace.py would hold the board for the next stage. A process
    killed by a signal gets the shell's status, 128 plus the signal number.
    """
    env = {
        **os.environ,
        "PYTHONPATH": os.pathsep.join(filter(None, ["src", os.environ.get("PYTHONPATH")])),
    }
    process = subprocess.Popen(
        command, stdout=log, stderr=subprocess.STDOUT, env=env, start_new_session=True
    )
    timed_out = False
    try:
        process.wait(timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
    finally:
        _stop_group(process)
    code = process.returncode
    return (code if code >= 0 else 128 - code), timed_out


def _stop_group(process: subprocess.Popen[bytes]) -> None:
    """SIGTERM the process group, then SIGKILL what is left after `STOP_GRACE` seconds.

    `ProcessLookupError` means the group is empty. macOS raises `PermissionError` instead when
    only zombies are left, which no signal can reach either. A second Ctrl-C waits until the group
    is gone, so it cannot leave an OpenOCD holding the board.
    """
    previous = signal.signal(signal.SIGINT, signal.SIG_IGN)
    try:
        with suppress(ProcessLookupError, PermissionError):
            os.killpg(process.pid, signal.SIGTERM)
            deadline = time.monotonic() + STOP_GRACE
            while time.monotonic() < deadline:
                process.poll()  # reap the leader, or it stays a member as a zombie
                os.killpg(process.pid, 0)  # raises once the group is empty
                time.sleep(0.2)
            os.killpg(process.pid, signal.SIGKILL)
        process.wait()
    finally:
        signal.signal(signal.SIGINT, previous)


def _now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


class Run:
    """One configuration's stages, kept in its scratch folder until the result is published.

    Scratch layout: `run/` (generated TOML, logs, times, failures, provenance), `trial-0/` (the
    traces, then the mined grammars and `evaluation.json`), `resume-k/` (seed copies, TOML and
    traces of the k-th trace retry; never published) and `destination.txt`.
    """

    def __init__(
        self, config: Path, board: Board, gdb_port: int, max_retries: int, stage_timeout: float
    ) -> None:
        self.config = config
        self.board = board
        self.gdb_port = gdb_port
        self.max_retries = max_retries
        self.stage_timeout = stage_timeout
        self.scratch = layout.scratch_dir(config)
        self.run_dir = self.scratch / "run"
        self.trial = self.scratch / "trial-0"
        self.toml = self.run_dir / "configuration.toml"
        # The checks of trace.py, so a configuration error stops the config before any stage.
        values = load_config(config)
        basic = values["BASIC"]
        self.seeds = Path(basic["seed_directory"]).expanduser()
        self.binary = Path(basic["binary_file"]).expanduser()
        self.eval_directory = Path(basic["eval_directory"]).expanduser()
        uart = values["Connection"]["input_channel"] == "esp32-uart"
        self.port_role = UART if uart else ADAPTER
        options = self.binary.parent / "build.options.json"
        try:
            self.fqbn = json.loads(options.read_text(encoding="utf-8"))["fqbn"]
        except (OSError, ValueError, KeyError) as error:
            raise ConfigError(f"no fqbn in {options}; build the firmware first") from error

    @property
    def name(self) -> str:
        return self.scratch.name

    def prepare(self, out: Path) -> None:
        """Create the scratch folder and the generated TOML, and record the destination root.

        A continued run keeps its TOML: if the configuration changed since, the traces so far were
        made with the old one, so the run stops instead of mixing the two.
        """
        self.run_dir.mkdir(parents=True, exist_ok=True)
        text = generated_toml(self.config, self.scratch)
        if not self.toml.exists():
            self.toml.write_text(text, encoding="utf-8")
        elif self.toml.read_text(encoding="utf-8") != text:
            raise ConfigError(f"{self.config} changed since this trial started; use --fresh")
        (self.scratch / "destination.txt").write_text(f"{out}\n", encoding="utf-8")

    def execute(self) -> None:
        """Run every stage that has not finished in an earlier start.

        Mining and evaluation count as finished when `times.txt` records exit 0: their output files
        exist while they are written. The board is always flashed first, as another configuration
        may have been flashed since.
        """
        self.flash()
        if not self._finished("mine"):
            self.trace()
            check_traces(self.seeds, self.trial)
            self._retry("mine", lambda: self._stage("mine", self._command(MINE, self.toml)))
        if not self._finished("eval"):
            out = ["--out", str(self.trial / "evaluation.json")]
            self._retry(
                "eval", lambda: self._stage("eval", self._command(EVALUATE, self.toml, out))
            )

    def publish(self, out: Path) -> Path:
        """Copy the trial and `run/` to the destination, delete the scratch folder, return it.

        N is computed again here, so a folder created since the preview bumps it. The copy is
        made beside the destination and renamed, so an interrupted copy never looks like a result.
        """
        destination = layout.destination(out, self.config)
        partial = destination.with_name(f"{destination.name}.partial")
        if partial.exists():
            shutil.rmtree(partial)
        shutil.copytree(self.trial, partial)
        shutil.copytree(self.run_dir, partial / "run")
        partial.rename(destination)
        shutil.rmtree(self.scratch)
        return destination

    def flash(self) -> None:
        self._retry("flash", lambda: self._stage("flash", self._flash_command()))
        time.sleep(FLASH_SETTLE)

    def trace(self) -> None:
        """Trace every seed, then resume with the missing seeds after each failure."""
        failed = False
        if not self.trial.exists():
            failed = not self._stage("trace", self._command(TRACE, self.toml))
            self.trial.mkdir(exist_ok=True)  # trace.py stopped before creating it
        for folder in sorted(self.scratch.glob("resume-*")):
            merge_traces(folder, self.trial)  # a resume whose runner stopped before its merge
        retries = 0
        while missing := missing_seeds(self.seeds, self.trial):
            if failed:
                retries = self._count_failure("trace", retries)
                self.flash()
            ok = self._resume(missing)
            progress = len(missing_seeds(self.seeds, self.trial)) < len(missing)
            if progress:
                retries = 0
            failed = not (ok and progress)

    def _resume(self, missing: list[Path]) -> bool:
        k = len(list(self.scratch.glob("resume-*"))) + 1
        folder = self.scratch / f"resume-{k}"
        seeds = folder / "seeds"
        seeds.mkdir(parents=True)
        for seed in missing:
            shutil.copy2(seed, seeds)
        toml = folder / "configuration.toml"
        toml.write_text(generated_toml(self.config, folder, seeds), encoding="utf-8")
        names = " ".join(seed.name for seed in missing)
        print(f"{self.name}: resume-{k} with {len(missing)} seeds: {names}", flush=True)
        try:
            return self._stage(f"resume-{k}", self._command(TRACE, toml))
        finally:
            merge_traces(folder, self.trial)  # also the traces of an interrupted resume

    def _flash_command(self) -> list[str]:
        """`arduino-cli upload` of the build next to `binary_file`, for the board's `fqbn`."""
        arduino_cli = shutil.which("arduino-cli")
        if arduino_cli is None:
            raise ConfigError("arduino-cli is not on PATH")
        port = self.board.paths()[self.port_role]
        build = str(self.binary.parent.resolve())
        sketch = str(self.config.parent.parent)
        return [arduino_cli, "upload", "-b", self.fqbn, "-p", port, "--input-dir", build, sketch]

    def _command(self, script: str, toml: Path, extra: list[str] | None = None) -> list[str]:
        """`script` with the TOML, `extra` and the board flags at their current paths."""
        port = self.board.paths()[self.port_role]
        board = ["--port", port, "--adapter-serial", self.board.serials[ADAPTER]]
        board += ["--gdb-port", str(self.gdb_port)]
        return [sys.executable, script, "--config", str(toml), *(extra or []), *board]

    def _stage(self, label: str, command: list[str]) -> bool:
        """Run one stage attempt; log it to `run/<label>.log`, `commands.txt` and `times.txt`."""
        log = self.run_dir / f"{label}.log"
        print(f"{self.name}: {label}", flush=True)
        with (self.run_dir / "commands.txt").open("a", encoding="utf-8") as file:
            file.write(f"{_now()} {label}: {shlex.join(command)}\n")
        start = time.monotonic()
        code, timed_out = 128 + signal.SIGINT, False  # kept if Ctrl-C stops the stage
        try:
            with log.open("a", encoding="utf-8") as file:
                file.write(f"=== {_now()} {shlex.join(command)}\n")
                file.flush()
                code, timed_out = run_in_group(command, file, self.stage_timeout)
        except KeyboardInterrupt:
            self._failure(f"{label} interrupted", log)
            raise
        finally:
            seconds = round(time.monotonic() - start)
            with (self.run_dir / "times.txt").open("a", encoding="utf-8") as file:
                status = "timeout" if timed_out else code  # a child may exit 0 when stopped
                file.write(f"{label} exit={status} seconds={seconds}\n")
        if timed_out:
            self._failure(f"{label} timed out after {self.stage_timeout / 3600:g} h", log)
        elif code:
            self._failure(f"{label} exit {code}", log)
        return code == 0 and not timed_out

    def _finished(self, label: str) -> bool:
        """Whether `times.txt` records exit 0 for `label`, written only after the stage ended."""
        times = self.run_dir / "times.txt"
        lines = times.read_text(encoding="utf-8").splitlines() if times.exists() else []
        return any(line.startswith(f"{label} exit=0 ") for line in lines)

    def _retry(self, label: str, attempt: Callable[[], bool]) -> None:
        retries = 0
        while not attempt():
            retries = self._count_failure(label, retries)

    def _count_failure(self, label: str, retries: int) -> int:
        """The retry count after a failure; raises `StageFailed` past `max_retries`."""
        if unplugged := self.board.unplugged():
            self._failure(f"{label}: {', '.join(unplugged)} unplugged; not counted as a retry")
            return retries
        if retries >= self.max_retries:
            raise StageFailed(f"{label} failed {retries + 1} times in a row")
        time.sleep(RETRY_PAUSE)
        return retries + 1

    def _failure(self, message: str, log: Path | None = None) -> None:
        """Print a failure and append it to `run/failures.log` with the end of the stage log."""
        print(f"{self.name}: {message}", flush=True)
        lines = [f"{_now()} {message}"]
        if log is not None and log.exists():
            tail = log.read_text(encoding="utf-8", errors="replace").splitlines()[-6:]
            lines += [f"    | {line}" for line in tail]
        with (self.run_dir / "failures.log").open("a", encoding="utf-8") as file:
            file.write("\n".join(lines) + "\n")
