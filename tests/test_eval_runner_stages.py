"""Resume logic of the evaluation runner: uv run pytest tests/test_eval_runner_stages.py."""

import os
import sys
import time
from pathlib import Path
from unittest.mock import patch

import pytest

from scripts.eval_runner import stages

C3_CGI = Path("example_firmware/esp32-c3_cgidecode/configuration/configuration.1-cable.toml")


def make_files(folder: Path, *names: str) -> Path:
    """Create `names` in `folder`; a `.trace` holds whole JSON, anything else its own name."""
    folder.mkdir(parents=True)
    for name in names:
        (folder / name).write_text("[]" if name.endswith(".trace") else name)
    return folder


def test_missing_seeds(tmp_path: Path):
    seeds = make_files(tmp_path / "seeds", "seed.1.in", "seed.2.in", "seed.3.in", "seed.10.in")
    (seeds / "subfolder").mkdir()
    trial = make_files(tmp_path / "trial-0", "seed.2.in.trace", "seed.3.in.trace", "out.log")
    (trial / "seed.3.in.trace").write_text('[{"line": 1')  # stopped while it was written
    missing = stages.missing_seeds(seeds, trial)
    assert [seed.name for seed in missing] == ["seed.1.in", "seed.10.in", "seed.3.in"]


def test_merge_traces(tmp_path: Path):
    trial = make_files(tmp_path / "trial-0", "seed.1.in.trace", "seed.3.in.trace", "out.log")
    (trial / "seed.1.in.trace").write_text('[{"kept": 1}]')
    (trial / "seed.3.in.trace").write_text("[")  # an interrupted copy
    resume = tmp_path / "resume-1"
    make_files(resume / "trial-0", "seed.1.in.trace", "seed.2.in.trace", "seed.3.in.trace")
    make_files(resume / "trial-1", "seed.4.in.trace")
    (resume / "trial-1/seed.4.in.trace").write_text("[")  # stopped while it was written

    copies = stages.merge_traces(resume, trial)

    assert copies == [trial / "seed.2.in.trace", trial / "seed.3.in.trace"]
    assert (trial / "seed.1.in.trace").read_text() == '[{"kept": 1}]'
    assert (trial / "seed.3.in.trace").read_text() == "[]"
    assert not (trial / "seed.4.in.trace").exists()
    assert (trial / "out.log").read_text() == "out.log"


def test_check_traces_follows_the_pairing_of_mine(tmp_path: Path):
    seeds = make_files(tmp_path / "seeds", "seed.1.in", "seed.2.in")
    trial = make_files(tmp_path / "trial-0", "seed.1.in.trace")
    with pytest.raises(stages.ConfigError, match="trace of None with the seed seed.2.in"):
        stages.check_traces(seeds, trial)
    (trial / "seed.2.in.trace").write_text("[]")
    stages.check_traces(seeds, trial)
    # Same names, other order: "a-1.trace" sorts before "a.trace", but "a" before "a-1".
    seeds = make_files(tmp_path / "named", "a", "a-1")
    trial = make_files(tmp_path / "named-trial", "a.trace", "a-1.trace")
    with pytest.raises(stages.ConfigError, match="trace of a-1 with the seed a$"):
        stages.check_traces(seeds, trial)


def test_generated_toml(tmp_path: Path):
    text = stages.generated_toml(C3_CGI, tmp_path / "resume-1", tmp_path / "resume-1/seeds")
    assert text.startswith(f"# Generated by scripts/eval_runner from {C3_CGI}: ")
    assert f'\noutput_directory = "{tmp_path}/resume-1"\n' in text
    assert f'\nseed_directory = "{tmp_path}/resume-1/seeds"\n' in text
    kept = stages.generated_toml(C3_CGI, tmp_path)
    assert '\nseed_directory = "./example_firmware/esp32-c3_cgidecode/seeds"\n' in kept


def test_run_in_group_stops_children_on_timeout(tmp_path: Path):
    pid_file = tmp_path / "child.pid"
    # The parent starts a child that ignores the parent's end, as OpenOCD under trace.py does.
    script = (
        "import subprocess, sys, time; "
        "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)']); "
        f"open({str(pid_file)!r}, 'w').write(str(child.pid)); time.sleep(60)"
    )
    with (tmp_path / "log").open("w") as log, patch.object(stages, "STOP_GRACE", 2):
        code, timed_out = stages.run_in_group([sys.executable, "-c", script], log, timeout=2)
    assert timed_out
    assert code == 128 + 15
    child = int(pid_file.read_text())
    time.sleep(0.5)  # the child is reparented and reaped by init
    with pytest.raises(ProcessLookupError):
        os.kill(child, 0)
